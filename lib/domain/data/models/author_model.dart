import 'package:sotaynamduoc/domain/data/entities/author_entity.dart';

class AuthorModel extends AuthorEntity {
  AuthorModel({
    super.id,
    super.name,
    super.slug,
    super.alias,
    super.biography,
    super.career,
    super.achievements,
    super.contributions,
    super.works,
    super.philosophy,
    super.legacy,
    super.birthDate,
    super.deathDate,
    super.birthPlace,
    super.deathPlace,
    super.era,
    super.dynasty,
    super.specialty,
    super.teacher,
    super.students,
    super.portrait,
    super.avatar,
    super.coverImage,
    super.galleryImages,
    super.quotes,
    super.anecdotes,
    super.honors,
    super.memorials,
    super.references,
    super.viewCount,
    super.likeCount,
    super.isActive,
    super.createdAt,
    super.updatedAt,
  });

  factory AuthorModel.fromJson(Map<String, dynamic> json) {
    return AuthorModel(
      id: json['id']?.toString(),
      name: json['name']?.toString(),
      slug: json['slug']?.toString(),
      alias: json['alias']?.toString(),
      biography: json['biography']?.toString(),
      career: json['career']?.toString(),
      achievements: json['achievements']?.toString(),
      contributions: json['contributions']?.toString(),
      works: json['works']?.toString(),
      philosophy: json['philosophy']?.toString(),
      legacy: json['legacy']?.toString(),
      birthDate: json['birthDate'] != null ? DateTime.parse(json['birthDate']) : null,
      deathDate: json['deathDate'] != null ? DateTime.parse(json['deathDate']) : null,
      birthPlace: json['birthPlace']?.toString(),
      deathPlace: json['deathPlace']?.toString(),
      era: json['era']?.toString(),
      dynasty: json['dynasty']?.toString(),
      specialty: json['specialty']?.toString(),
      teacher: json['teacher']?.toString(),
      students: json['students']?.toString(),
      portrait: json['portrait']?.toString(),
      avatar: json['avatar']?.toString(),
      coverImage: json['coverImage']?.toString(),
      galleryImages: json['galleryImages'] != null 
          ? List<String>.from(json['galleryImages'])
          : null,
      quotes: json['quotes']?.toString(),
      anecdotes: json['anecdotes']?.toString(),
      honors: json['honors']?.toString(),
      memorials: json['memorials']?.toString(),
      references: json['references']?.toString(),
      viewCount: json['viewCount']?.toInt(),
      likeCount: json['likeCount']?.toInt(),
      isActive: json['isActive'],
      createdAt: json['createdAt'] != null ? DateTime.parse(json['createdAt']) : null,
      updatedAt: json['updatedAt'] != null ? DateTime.parse(json['updatedAt']) : null,
    );
  }

  factory AuthorModel.fromEntity(AuthorEntity entity) {
    return AuthorModel(
      id: entity.id,
      name: entity.name,
      slug: entity.slug,
      alias: entity.alias,
      biography: entity.biography,
      career: entity.career,
      achievements: entity.achievements,
      contributions: entity.contributions,
      works: entity.works,
      philosophy: entity.philosophy,
      legacy: entity.legacy,
      birthDate: entity.birthDate,
      deathDate: entity.deathDate,
      birthPlace: entity.birthPlace,
      deathPlace: entity.deathPlace,
      era: entity.era,
      dynasty: entity.dynasty,
      specialty: entity.specialty,
      teacher: entity.teacher,
      students: entity.students,
      portrait: entity.portrait,
      avatar: entity.avatar,
      coverImage: entity.coverImage,
      galleryImages: entity.galleryImages,
      quotes: entity.quotes,
      anecdotes: entity.anecdotes,
      honors: entity.honors,
      memorials: entity.memorials,
      references: entity.references,
      viewCount: entity.viewCount,
      likeCount: entity.likeCount,
      isActive: entity.isActive,
      createdAt: entity.createdAt,
      updatedAt: entity.updatedAt,
    );
  }

  AuthorEntity toEntity() {
    return AuthorEntity(
      id: id,
      name: name,
      slug: slug,
      alias: alias,
      biography: biography,
      career: career,
      achievements: achievements,
      contributions: contributions,
      works: works,
      philosophy: philosophy,
      legacy: legacy,
      birthDate: birthDate,
      deathDate: deathDate,
      birthPlace: birthPlace,
      deathPlace: deathPlace,
      era: era,
      dynasty: dynasty,
      specialty: specialty,
      teacher: teacher,
      students: students,
      portrait: portrait,
      avatar: avatar,
      coverImage: coverImage,
      galleryImages: galleryImages,
      quotes: quotes,
      anecdotes: anecdotes,
      honors: honors,
      memorials: memorials,
      references: references,
      viewCount: viewCount,
      likeCount: likeCount,
      isActive: isActive,
      createdAt: createdAt,
      updatedAt: updatedAt,
    );
  }
} 